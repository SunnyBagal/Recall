// Writes eval/RESULTS.md from eval/results/*.json. Every number in the file comes
// from those JSON files, which the scripts in this folder produce.
//
//   bun --no-env-file run eval/report.ts
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { EVAL_DIR, RESULTS_DIR } from "./lib";

const load = (name: string) => {
  const path = join(RESULTS_DIR, name);
  return existsSync(path) ? JSON.parse(readFileSync(path, "utf8")) : null;
};

const before = load("results-before.json");
const after = load("results-after.json");
const vlBefore = load("vector-latency-before.json");
const vlAfter = load("vector-latency-after.json");
const fts = load("fts-variants.json");
const dry = load("ingest-stats-dry-run.json");
const full = load("ingest-stats.json");
if (!before || !vlBefore || !fts || !dry || !full) throw new Error("missing results: run the commands in RESULTS.md");

// Published list prices, checked 2026-11-01. Haiku 4.5 is the model aiProcessor.ts calls.
const PRICE = { haikuIn: 1, haikuOut: 5, embed: 0.02 };

const m = (x: number) => x.toFixed(4);
const ms = (x: number) => x.toFixed(2);
const pct = (x: number | null) => (x === null ? "n/a" : `${(x * 100).toFixed(1)}%`);
const usd = (x: number) => `$${x.toFixed(2)}`;
const tok = (x: number) => Math.round(x).toLocaleString("en-US");
const short = (sha: string) => sha.slice(0, 7);
const MODES = ["fts", "vector", "hybrid"] as const;
const NAMES = { fts: "FTS only", vector: "Vector only", hybrid: "Hybrid" };

const lines: string[] = [];
const push = (...l: string[]) => lines.push(...l);
const table = (head: string[], rows: string[][]) =>
  push(`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.join(" | ")} |`), "");

const qualityRows = (r: any) =>
  MODES.map((mode) => {
    const x = r.modes[mode];
    return [NAMES[mode], m(x.ndcg), m(x.recall), m(x.mrr), `${x.queriesWithNoResults}/${r.queries}`];
  });

const latencyRows = (r: any) =>
  MODES.map((mode) => {
    const x = r.modes[mode];
    return [
      NAMES[mode],
      ms(x.latencyFirstRun.p50), ms(x.latencyFirstRun.p95),
      ms(x.latencyWarm.p50), ms(x.latencyWarm.p95),
    ];
  });

push(
  "# Retrieval eval: BEIR SciFact",
  "",
  "Generated by `eval/report.ts` from `eval/results/*.json`. Do not edit by hand.",
  "",
);

// ---- quality ---------------------------------------------------------------
const qHead = ["Mode", "nDCG@10", "Recall@10", "MRR@10", "Queries with no results"];
if (after) {
  push("## Quality: before and after", "");
  table(
    ["Mode", "nDCG@10 before", "nDCG@10 after", "Recall@10 before", "Recall@10 after", "MRR@10 before", "MRR@10 after", "No results before", "No results after"],
    MODES.map((mode) => {
      const b = before.modes[mode];
      const a = after.modes[mode];
      return [
        NAMES[mode], m(b.ndcg), m(a.ndcg), m(b.recall), m(a.recall), m(b.mrr), m(a.mrr),
        `${b.queriesWithNoResults}/${before.queries}`, `${a.queriesWithNoResults}/${after.queries}`,
      ];
    }),
  );
  const c = after.hybridVsVectorNdcg;
  push(
    `Hybrid against vector only, after, per query on nDCG@10: ${c.wins} better, ${c.losses} worse, ${c.ties} tied.`,
    `Before: ${before.hybridVsVectorNdcg.wins} better, ${before.hybridVsVectorNdcg.losses} worse, ${before.hybridVsVectorNdcg.ties} tied.`,
    "",
  );
} else {
  push("## Quality: before (current search behaviour)", "");
  table(qHead, qualityRows(before));
  const c = before.hybridVsVectorNdcg;
  push(`Hybrid against vector only, per query on nDCG@10: ${c.wins} better, ${c.losses} worse, ${c.ties} tied.`, "");
}

// ---- latency ---------------------------------------------------------------
const latHead = ["Mode", "First run p50", "First run p95", "Warm p50", "Warm p95"];
push("## Latency through `hybridSearch` (ms)", "");
push("### Before", "");
table(latHead, latencyRows(before));
if (after) {
  push("### After", "");
  table(latHead, latencyRows(after));
}
push(
  "Database and fusion time only. The `/search` route also makes one OpenAI embedding call per request, which is not included.",
  "",
);

// ---- seq scan vs HNSW ------------------------------------------------------
const ARM_NAMES: Record<string, string> = {
  exact: "Seq scan (exact)",
  production: "`hybridSearch` vector mode (code at that commit)",
  "hnsw-40-override": "HNSW, override, no iterative scan",
  "iterative-no-override": "Iterative scan, no override (planner chooses)",
};
const TENANT_NAMES = (r: any): Record<string, string> => ({
  whole: `One user owns every row (${r.corpusRows})`,
  medium: `User owns ${r.rowsByTenantInClone.medium} of ${r.corpusRows} rows`,
  tiny: `User owns ${r.rowsByTenantInClone.tiny} of ${r.corpusRows} rows`,
});
const vectorTables = (r: any, title: string) => {
  push(`### ${title} (commit \`${short(r.gitCommit)}\`)`, "");
  const names = TENANT_NAMES(r);
  for (const tenant of ["whole", "medium", "tiny"]) {
    push(`**${names[tenant]}**`, "");
    table(
      ["Path", "Warm p50 (ms)", "Warm p95 (ms)", "Exact top 10 returned", "Queries matching exact list", "Mean rows"],
      Object.keys(ARM_NAMES).map((arm) => {
        const x = r.tenants[tenant][arm];
        return [
          ARM_NAMES[arm]!, ms(x.p50), ms(x.p95), pct(x.correctShareOfExactTop10),
          `${x.queriesWithExactSameList}/${r.queries}`, x.meanRowsReturned.toFixed(2),
        ];
      }),
    );
  }
};
push("## Vector arm: seq scan against HNSW, with correctness", "");
vectorTables(vlBefore, "Before");
if (vlAfter) vectorTables(vlAfter, "After");
push(
  `Each row is ${vlBefore.queries} queries × ${vlBefore.passes} timed passes after one discarded warm-up pass.`,
  "All paths apply the production 0.3 similarity cutoff. The whole-table row has the same shape as the earlier",
  "`docs/explain` measurement: one user owning nearly every row. The earlier ratio does not carry over to smaller users.",
  "",
);

// ---- notes -----------------------------------------------------------------
const b = before.modes;
const tiny = vlBefore.tenants.tiny;
push(
  "## What the before numbers show",
  "",
  `- **FTS was nearly unusable on natural-language queries.** ${b.fts.queriesWithNoResults} of ${before.queries} test queries returned nothing, because every term had to match.`,
  `- **Hybrid had almost nothing to fuse,** so it matched vector only: nDCG@10 ${m(b.hybrid.ndcg)} against ${m(b.vector.ndcg)}.`,
  `- **Smaller users lost most of their vector results.** A user with ${vlBefore.rowsByTenantInClone.tiny} rows got ${pct(tiny.production.correctShareOfExactTop10)} of the exact top 10, averaging ${tiny.production.meanRowsReturned.toFixed(2)} rows against ${tiny.exact.meanRowsReturned.toFixed(2)} from an exact search.`,
  "",
);

push("## How the FTS fix was chosen", "");
push(`Compared on the ${fts.queries}-query **train** split (\`eval/fts-variants.ts\`), so the test split above played no part.`, "");
table(
  ["Variant", "nDCG@10", "Recall@10", "MRR@10", "No results", "p50 (ms)", "p95 (ms)"],
  Object.entries<any>(fts.variants).map(([name, x]) => [
    name, m(x.ndcg), m(x.recall), m(x.mrr), `${x.queriesWithNoResults}/${fts.queries}`, ms(x.p50), ms(x.p95),
  ]),
);

// ---- cost ------------------------------------------------------------------
const d = dry.uncachedCallsThisRun;
const f = full.uncachedCallsThisRun;
const cost = (i: number, o: number, e: number) => (i * PRICE.haikuIn + o * PRICE.haikuOut + e * PRICE.embed) / 1e6;
const N = full.rows;
const totalIn = d.summaryInputTokens + f.summaryInputTokens;
const totalOut = d.summaryOutputTokens + f.summaryOutputTokens;
const totalEmbed = d.embeddingTokens + f.embeddingTokens;
const projected = cost(
  (d.summaryInputTokens / dry.rows) * N,
  (d.summaryOutputTokens / dry.rows) * N,
  (d.embeddingTokens / dry.rows) * N,
);
push(
  "## Ingest and cost",
  "",
  `Prices: Haiku 4.5 $${PRICE.haikuIn}/$${PRICE.haikuOut} per million input/output tokens, text-embedding-3-small $${PRICE.embed} per million (list prices, checked 2026-11-01). Costs are calculated from token counts, not taken from a bill.`,
  "",
);
table(
  ["", "Haiku input", "Haiku output", "Embedding", "Cost"],
  [
    [`Dry run, ${dry.rows} docs (actual)`, tok(d.summaryInputTokens), tok(d.summaryOutputTokens), tok(d.embeddingTokens), usd(cost(d.summaryInputTokens, d.summaryOutputTokens, d.embeddingTokens))],
    [`Projection for ${N} docs`, tok((d.summaryInputTokens / dry.rows) * N), tok((d.summaryOutputTokens / dry.rows) * N), tok((d.embeddingTokens / dry.rows) * N), usd(projected)],
    [`Actual, ${N} docs + ${before.queries} queries, including the dry run`, tok(totalIn), tok(totalOut), tok(totalEmbed), usd(cost(totalIn, totalOut, totalEmbed))],
  ],
);
push(
  `Full run: ${full.done}/${full.rows} rows done, ${full.with_embedding} with embeddings, ${full.failedJobs} failed jobs, ${full.without_tags} with no tags (the summarizer's parse-failure signal), ${full.seconds}s at worker concurrency ${full.workerConcurrency}.`,
  "",
);

// ---- methodology -----------------------------------------------------------
const dx = before.diagnostics;
push(
  "## Methodology",
  "",
  `- **Dataset:** BEIR SciFact, ${dx.corpusRows} documents, the ${before.queries} queries in \`qrels/test.tsv\`. Binary labels. Queries that return nothing score 0 and stay in the averages.`,
  `- **Metrics:** k = ${before.k}, last timed pass. Rankings changed between passes for ${before.modes.fts.queriesWithChangedRankingBetweenPasses}/${before.modes.vector.queriesWithChangedRankingBetweenPasses}/${before.modes.hybrid.queriesWithChangedRankingBetweenPasses} queries (FTS/vector/hybrid) before${after ? ` and ${after.modes.fts.queriesWithChangedRankingBetweenPasses}/${after.modes.vector.queriesWithChangedRankingBetweenPasses}/${after.modes.hybrid.queriesWithChangedRankingBetweenPasses} after` : ""}.`,
  "- **Ingestion:** rows inserted as pending, jobs sent through BullMQ on local Redis, unmodified `processContent` with real Haiku and OpenAI calls, cached to disk. `fetchMetadata` is skipped because the corpus has no URLs: title and og_title are the document title, extracted_text is the abstract. The worker ran at concurrency 12 with 6 attempts (production: 3 and 3).",
  "- **Search:** every mode calls `hybridSearch` from `services/searchService.ts`. FTS only passes a null embedding, vector only skips the keyword arm.",
  `- **Latency:** ${before.runsPerMode} sequential passes over all queries per mode. Before each mode Postgres restarts and a new Bun process starts. Pass 1 is reported as first run, passes 2 and 3 pooled as warm. The connection is opened before timing starts. p50 and p95 are nearest-rank.`,
  "- **\"First run\" is not fully cold.** Postgres shared buffers and the Bun process are cold, but the macOS file cache survives a Postgres restart and clearing it needs sudo.",
  `- **Environment:** Postgres ${dx.server}, pgvector ${dx.pgvector}, shared_buffers ${dx.sharedBuffers}, default hnsw.ef_search ${dx.efSearch}, HNSW m=16, ef_construction=64, on ${before.machine.cpu} (${before.machine.cores} cores, ${before.machine.memGb} GB). Loopback connection. A developer laptop, not a production server, so compare the numbers with each other, not with production.`,
  `- **Commits:** before \`${short(before.gitCommit)}\`${after ? `, after \`${short(after.gitCommit)}\`` : ""}.`,
  `- **Scale:** ${dx.corpusRows} rows. Behaviour at larger sizes is not measured here.`,
  "",
);

push(
  "## Reproduce",
  "",
  "From `recall-backend/`. Needs Homebrew `postgresql@17`, `pgvector` and `redis`. Only `eval/ingest.ts` makes paid API calls, using `OPENAI_API_KEY` and `ANTHROPIC_API_KEY`, and it reuses `eval/cache/` when present.",
  "",
  "```bash",
  "eval/local-services.sh start",
  "bun --no-env-file run eval/download.ts",
  "bun run eval/ingest.ts --limit=100   # dry run: token counts for 100 docs",
  "bun run eval/ingest.ts               # full ingest; resets the local eval database",
  "bun --no-env-file run eval/fts-variants.ts",
  "",
  `git checkout ${short(before.gitCommit)} -- services/searchService.ts   # before`,
  "bun --no-env-file run eval/run.ts --label=before",
  "bun --no-env-file run eval/vector-latency.ts --label=before",
  ...(after
    ? [
        `git checkout ${short(after.gitCommit)} -- services/searchService.ts    # after`,
        "bun --no-env-file run eval/run.ts --label=after",
        "bun --no-env-file run eval/vector-latency.ts --label=after",
      ]
    : []),
  "bun --no-env-file run eval/report.ts",
  "```",
  "",
);

writeFileSync(join(EVAL_DIR, "RESULTS.md"), lines.join("\n"));
console.log(`wrote ${join(EVAL_DIR, "RESULTS.md")}`);
